import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

// Writes sw.js into the static export: the service worker that keeps the whole
// program on the visitor's computer after the first visit, so layerling starts
// without internet. It runs after `next build`, when the export's file names
// (with their content hashes) are final.
//
// The rules, all in serviceWorkerSource below:
// - Program files are stored on install. Those whose name carries their
//   content (/_next/static/, /occt/<version>/) are served from the computer;
//   the rest (icons, manifold, the Graphite stylesheet) come fresh while
//   online and from the stored copy offline.
// - The page itself (a navigation) always comes fresh from the server while
//   there is a connection - "reload the page to get the new version" keeps
//   working. Only offline, or after NAVIGATION_TIMEOUT_MS without an answer,
//   the stored page is used; it belongs to the stored program files.
// - The Japanese typeface (/fonts/japanese/<hash>/) is not stored on install:
//   most visitors never write Japanese. The first fetch of a file puts it in a
//   cache of its own, layerling-fonts, which lives across versions; only the
//   folders of other cuts are removed from it.
// - PHP (server storage, contact form) and the dev API never touch the cache.
// - The copies of the last KEEP_VERSIONS versions stay. A page that is still
//   open when a new version arrives keeps running on its own files: it loads
//   some of them only when needed (the CAD workers, for one), and by then the
//   deploy has removed them from the server. Deleting the old copy at once
//   made "finish sketch" fail with "worker failed to start" (discussion #88).

const repositoryRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const exportRoot = join(repositoryRoot, "apps", "web", ".next-export");

/**
 * Which exported files go into the offline copy, as site paths ("/x/y.js").
 * Left out: server scripts, files only crawlers read, source maps, and the
 * bundler's own copy of the CAD kernel under _next/static/media - the program
 * loads the kernel from /occt/<version>/, and a second 21 MB copy would only
 * double the download.
 */
export function precachePaths(relativeFiles) {
  const paths = [];
  for (const file of relativeFiles) {
    const path = "/" + file.split(sep).join("/");
    if (path.endsWith(".php")) continue;
    if (path.endsWith(".map")) continue;
    // version.json is what an open page asks for to learn that a new version arrived: never stored.
    if (path === "/sw.js" || path === "/version.json" || path === "/index.txt" || path === "/robots.txt" || path === "/sitemap.xml") continue;
    if (path === "/404.html" || path.startsWith("/404/")) continue;
    if (path.startsWith("/_next/static/media/") && path.endsWith(".wasm")) continue;
    // Fetched when a text needs Japanese; the service worker stores it then (FONT_CACHE).
    if (path.startsWith("/fonts/japanese/")) continue;
    // The guide's pages are small text and worth having offline; its pictures
    // are not, and would triple the download for a page few people open. Every
    // language has its own folder (guideDir in languages.ts), so any top folder
    // counts: only three were named here, and 16 more went into the cache.
    if (/^\/[^/]+\/img\//.test(path)) continue;
    // The page with every chapter in a row is for printing: about 400 KB per language, opened by few.
    if (/^\/[^/]+\/print-all\.html$/.test(path)) continue;
    paths.push(path === "/index.html" ? "/" : path);
  }
  return paths.sort();
}

/**
 * version.json: what a page that is already open asks for now and then. A different build means a
 * deploy happened since it loaded, and it offers a reload. The titles of the newest highlights go
 * along so the offer can say what is new.
 */
export function versionFileSource(packageVersion, build, whatsNewEntries) {
  const highlights = whatsNewEntries.slice(0, 12).flatMap((entry) => entry.items.map((item) => ({ version: entry.version, title: item.title })));
  return JSON.stringify({ version: packageVersion, build, highlights });
}

export function serviceWorkerSource(version, paths) {
  return `// Generated by scripts/generate-service-worker.mjs - do not edit.
// Keeps layerling on this computer so it also starts without internet.
const VERSION = ${JSON.stringify(version)};
const CACHE = "layerling-" + VERSION;
const PRECACHE = ${JSON.stringify(paths)};
const PRECACHED = new Set(PRECACHE);
const NAVIGATION_TIMEOUT_MS = 4000;
const KEEP_VERSIONS = 3;
const META_CACHE = "layerling-meta";
const FONT_CACHE = "layerling-fonts";
const VERSIONS_KEY = "/__layerling-versions";

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // "no-cache" asks the server, so the offline copy never mixes in an older
    // file the browser still had in its normal cache.
    await cache.addAll(PRECACHE.map((path) => new Request(path, { cache: "no-cache" })));
    await self.skipWaiting();
  })());
});

// The versions in the order they arrived, newest last; copies older than the
// last KEEP_VERSIONS are removed.
self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const meta = await caches.open(META_CACHE);
    const stored = await meta.match(VERSIONS_KEY);
    let versions = null;
    try {
      versions = stored ? await stored.json() : null;
    } catch {
      versions = null;
    }
    // No list yet: the copies already here belong to the version before this
    // one, written by a service worker that did not keep a list.
    if (!Array.isArray(versions)) {
      versions = (await caches.keys()).filter((name) => name.startsWith("layerling-") && name !== META_CACHE && name !== FONT_CACHE && name !== CACHE);
    }
    versions = [...versions.filter((name) => name !== CACHE), CACHE].slice(-KEEP_VERSIONS);
    await meta.put(VERSIONS_KEY, new Response(JSON.stringify(versions), { headers: { "content-type": "application/json" } }));
    const keep = new Set([...versions, META_CACHE, FONT_CACHE]);
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith("layerling-") && !keep.has(name)).map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

function isNeverCached(url) {
  return url.pathname.endsWith(".php") || url.pathname.startsWith("/api/");
}

async function fromNetworkOrStoredPage(request) {
  const url = new URL(request.url);
  const storedPath = PRECACHED.has(url.pathname) ? url.pathname : "/";
  let timer;
  const timeout = new Promise((resolve) => {
    timer = setTimeout(() => resolve(null), NAVIGATION_TIMEOUT_MS);
  });
  try {
    const response = await Promise.race([fetch(request).catch(() => null), timeout]);
    if (response) return response;
  } finally {
    clearTimeout(timer);
  }
  const stored = await caches.match(storedPath, { cacheName: CACHE });
  return stored || fetch(request);
}

// Files whose name changes with their content never go stale.
function isImmutable(path) {
  return path.startsWith("/_next/static/") || /^\\/occt\\/[^/]+\\//.test(path);
}

// Looked up in every kept copy, so a page of an older version finds its files.
async function storedFirst(request, path) {
  const stored = await caches.match(path, { cacheName: CACHE }) || await caches.match(path);
  return stored || fetch(request);
}

// Everything else keeps its name across versions; while online it comes fresh
// from the server, offline from the stored copy.
async function networkFirst(request, path) {
  try {
    const response = await fetch(request);
    if (response.ok) return response;
  } catch {
    // offline - fall through to the stored copy
  }
  const stored = await caches.match(path, { cacheName: CACHE });
  return stored || fetch(request);
}

// The Japanese typeface: stored by the first fetch, and from then on served from here. The files
// of an older cut (another <hash> folder) are removed once a new one is stored.
function isJapaneseFont(path) {
  return /^\\/fonts\\/japanese\\/[^/]+\\/[^/]+$/.test(path);
}

async function fontFirst(request, path) {
  const cache = await caches.open(FONT_CACHE);
  const stored = await cache.match(path);
  if (stored) return stored;
  const response = await fetch(request);
  if (response.ok) {
    const folder = path.slice(0, path.lastIndexOf("/") + 1);
    for (const key of await cache.keys()) {
      const other = new URL(key.url).pathname;
      if (!other.startsWith(folder)) await cache.delete(key);
    }
    await cache.put(path, response.clone());
  }
  return response;
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || isNeverCached(url)) return;
  if (request.mode === "navigate") {
    event.respondWith(fromNetworkOrStoredPage(request));
    return;
  }
  // Stored files are looked up without their query: the Graphite stylesheet
  // carries ?v=<version> only to get past the browser's normal cache.
  if (isJapaneseFont(url.pathname)) {
    event.respondWith(fontFirst(request, url.pathname));
  } else if (isImmutable(url.pathname)) {
    event.respondWith(storedFirst(request, url.pathname));
  } else if (PRECACHED.has(url.pathname)) {
    event.respondWith(networkFirst(request, url.pathname));
  }
});
`;
}

async function listFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map((entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? listFiles(path) : [path];
  }));
  return nested.flat();
}

async function main() {
  const files = (await listFiles(exportRoot)).map((path) => relative(exportRoot, path));
  const paths = precachePaths(files);
  // The version follows the content, so every deploy that changes a file
  // installs a fresh offline copy - and one that changes nothing keeps it.
  const hash = createHash("sha256");
  for (const path of paths) {
    const file = path === "/" ? "index.html" : path.slice(1);
    hash.update(path);
    hash.update(await readFile(join(exportRoot, file)));
  }
  const version = hash.digest("hex").slice(0, 16);
  await writeFile(join(exportRoot, "sw.js"), serviceWorkerSource(version, paths));
  const packageJson = JSON.parse(await readFile(join(repositoryRoot, "package.json"), "utf8"));
  const whatsNew = JSON.parse(await readFile(join(repositoryRoot, "apps", "web", "src", "lib", "whatsNew.json"), "utf8"));
  await writeFile(join(exportRoot, "version.json"), versionFileSource(packageJson.version, version, whatsNew));
  console.log(`Service worker: ${paths.length} files for offline use, version ${version}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await main();
}
